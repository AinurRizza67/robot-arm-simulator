"""Builds app/scripts/00_icon_data.js from the Phosphor Icons package (regular weight, MIT license).

The icon names are collected from app/scripts/00_icons.js (icon: '...') and from EXTRA below.
Usage: python tools/build_icons.py <path to @phosphor-icons/core/assets/regular>
       (get it with: npm pack @phosphor-icons/core, then extract the .tgz)
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.join(HERE, "..", "app", "scripts")
EXTRA = [
    "arrows-out-cardinal",
    "chart-line-up",
    "info",
    "question",
    "warning",
    "sphere",
    "hand-pointing",
    "play-circle",
]


def main(src):
    rules = open(os.path.join(APP, "00_icons.js"), encoding="utf8").read()
    names = sorted(set(re.findall(r"icon: '([a-z0-9-]+)'", rules)) | set(EXTRA))
    out, missing = [], []
    for n in names:
        p = os.path.join(src, n + ".svg")
        if not os.path.exists(p):
            missing.append(n)
            continue
        svg = open(p, encoding="utf8").read()
        body = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1).strip()
        out.append("  '%s': '%s'" % (n, body.replace("'", "\\'")))
    if missing:
        raise SystemExit("missing icons: " + ", ".join(missing))
    head = (
        "/* 00_icon_data.js (generated by tools/build_icons.py, do not edit by hand)\n"
        "   SVG bodies from Phosphor Icons, regular weight, viewBox 0 0 256 256. MIT License, Copyright (c) 2023 Phosphor Icons. */\n"
    )
    with open(os.path.join(APP, "00_icon_data.js"), "w", encoding="utf8", newline="\n") as f:
        f.write(head + "const ICON_SVG = {\n" + ",\n".join(out) + "\n};\n")
    print(len(out), "icons")


if __name__ == "__main__":
    main(sys.argv[1])
